#include "delay.h"
#include "LED.h"
#include "USART1.h"
#include "USART2.h"

typedef struct {
    u8    uid[4];     /* 4字节卡号 */
    u8    txt[8];     /* GB2312播报字节 */
    u8    len;
} CardItem;

static const CardItem cards[] = {
    { {0xE1,0x4B,0x50,0xF2}, {0xB5,0xD8,0xC7,0xF2},        4 }, /* 地球 */
    { {0x01,0x6E,0x51,0xF2}, {0xD4,0xC2,0xC7,0xF2},        4 }, /* 月球 */
    { {0xF1,0xBC,0x50,0xF2}, {0xCB,0xAE,0xD0,0xC7},        4 }, /* 水星 */
    { {0xE1,0x47,0x50,0xF2}, {0xCC,0xAB,0xD1,0xF4},        4 }, /* 太阳 */
    { {0xC1,0xB5,0x4F,0xF2}, {0xBB,0xF0,0xD0,0xC7},        4 }, /* 火星 */
    { {0xD1,0x50,0x4F,0xF2}, {0xB9,0xC8,0xC9,0xF1,0xD0,0xC7}, 6 }, /* 谷神星 */
    { {0x11,0xB0,0x4E,0xF2}, {0xCD,0xC1,0xD0,0xC7},        4 }, /* 土星 */
    { {0xC1,0xB1,0x4F,0xF2}, {0xCC,0xEC,0xCD,0xF5,0xD0,0xC7}, 6 }, /* 天王星 */
    { {0xD1,0x4C,0x4F,0xF2}, {0xBA,0xA3,0xCD,0xF5,0xD0,0xC7}, 6 }, /* 海王星 */
    { {0x11,0xAC,0x4E,0xF2}, {0xDA,0xA4,0xCD,0xF5,0xD0,0xC7}, 6 }, /* 冥王星 */
    { {0xD1,0xAD,0x4F,0xF2}, {0xE3,0xD2,0xC9,0xF1,0xD0,0xC7}, 6 }, /* 阋神星 */
    { {0xE1,0x48,0x4F,0xF2}, {0xC4,0xF1,0xC9,0xF1,0xD0,0xC7}, 6 }, /* 鸟神星 */
    { {0x11,0xA8,0x4E,0xF2}, {0xC8,0xD1,0xC9,0xF1,0xD0,0xC7}, 6 }, /* 妊神星 */
    { {0xD1,0xA9,0x4F,0xF2}, {0xC4,0xBE,0xD0,0xC7},        4 }, /* 木星 */
    { {0xF1,0x44,0x4F,0xF2}, {0xBD,0xF0,0xD0,0xC7},        4 }, /* 金星 */
    { {0x11,0xA4,0x4E,0xF2}, {0xB5,0xD8,0xC7,0xF2},        4 }, /* 地球 */
};
#define CARD_NUM  (sizeof(cards) / sizeof(cards[0]))

static u8 uid_equal(const u8 *a, const u8 *b)
{
    return (a[0] == b[0] && a[1] == b[1] && a[2] == b[2] && a[3] == b[3]);
}

static void play_voice(const CardItem *item)
{
    u8 i;
    for (i = 0; i < item->len; i++) {
        usart2_voice_send_byte(item->txt[i]);   /* 播报GB2312字节 */
    }
}

int main(void)
{
    u8 uid[4];
    u8 i;

    delay_init();
    led_init();
    usart1_card_init(9600);   /* 读卡模组 */
    usart2_voice_init(9600);  /* 语音播报 */

    while (1) {
        if (usart1_card_new_uid()) {
            usart1_card_get_uid(uid);
            for (i = 0; i < CARD_NUM; i++) {
                if (uid_equal(cards[i].uid, uid)) {
                    play_voice(&cards[i]);
                    break;
                }
            }
            led_toggle();   /* 识别到卡片, LED状态翻转 */
        }
        delay_ms(5);
    }
}
